// Builds src/data/speciesImages.ts: one freely licensed Wikimedia Commons photo per species,
// with the author, licence and source page needed for attribution (TASL).
//
//   node scripts/fetch-species-images.mjs
//
// Picks each species' English Wikipedia lead image (free images only), then reads its
// licence metadata from Commons. Only public-domain / CC0 / CC BY / CC BY-SA files are
// accepted; anything else fails the run so it can be reviewed by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const UA = { 'User-Agent': 'exocat-visualizer-demo/0.1 (species image manifest)' };
const THUMB_WIDTH = 480;

/** Hand-picked files where the lead image's metadata is incomplete. */
const FILE_OVERRIDES = {
  'Harmonia axyridis': 'Asian multicolored lady beetle.jpg',
};
/** Cleaner author credits where the Commons "Artist" field is a paragraph. */
const ARTIST_OVERRIDES = {
  'Silurus glanis': 'Dieter Florian',
  'Procambarus clarkii': 'MikeMurphy',
  'Pseudorasbora parva': 'Seotaro (edited by Estrilda)',
  'Callinectes sapidus': 'Wendy Kaveney',
  'Ammotragus lervia': 'Rei (English Wikipedia)',
  'Harmonia axyridis': 'Scott Bauer, USDA ARS',
  'Sander lucioperca': 'eLNuko',
};
const ALLOWED = /^(public domain|cc0|pdm|cc by(-sa)? \d(\.\d)?( [a-z]{2})?)$/i;

const api = async (host, params) => {
  const q = new URLSearchParams({ action: 'query', format: 'json', formatversion: '2', ...params });
  const res = await fetch(`https://${host}/w/api.php?${q}`, { headers: UA });
  if (!res.ok) throw new Error(`${host}: HTTP ${res.status}`);
  return res.json();
};
const text = (html = '') => html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

const speciesSrc = readFileSync(new URL('src/data/species.ts', root), 'utf8');
const species = [...speciesSrc.matchAll(/id: '([^']+)', scientificName: '([^']+)'/g)].map(([, id, sci]) => ({ id, sci }));

// 1. Lead image per Wikipedia article (redirects followed, e.g. Neogale vison).
const wiki = await api('en.wikipedia.org', { redirects: '1', prop: 'pageimages', piprop: 'name', titles: species.map((s) => s.sci).join('|') });
const back = new Map();
for (const n of wiki.query.normalized ?? []) back.set(n.to, n.from);
for (const r of wiki.query.redirects ?? []) back.set(r.to, back.get(r.from) ?? r.from);
const leadFile = new Map(wiki.query.pages.map((p) => [back.get(p.title) ?? p.title, p.pageimage]));

// 2. Licence metadata from Commons.
const fileFor = (sci) => (FILE_OVERRIDES[sci] ?? leadFile.get(sci))?.replace(/_/g, ' ');
const commons = await api('commons.wikimedia.org', {
  prop: 'imageinfo',
  iiprop: 'url|size|extmetadata',
  iiurlwidth: String(THUMB_WIDTH),
  iiextmetadatafilter: 'Artist|LicenseShortName|LicenseUrl',
  titles: species.map((s) => `File:${fileFor(s.sci)}`).join('|'),
});
const info = new Map(commons.query.pages.map((p) => [p.title.replace(/^File:/, ''), p.imageinfo?.[0]]));

const out = {};
const problems = [];
for (const { id, sci } of species) {
  const file = fileFor(sci);
  const ii = file && info.get(file);
  if (!ii) { problems.push(`${sci}: no image`); continue; }
  const md = ii.extmetadata ?? {};
  const license = text(md.LicenseShortName?.value);
  if (!ALLOWED.test(license)) { problems.push(`${sci}: licence "${license}" not accepted`); continue; }
  const artist = ARTIST_OVERRIDES[sci] ?? text(md.Artist?.value);
  if (!artist) { problems.push(`${sci}: no author`); continue; }
  out[id] = {
    src: ii.thumburl,
    width: ii.thumbwidth,
    height: ii.thumbheight,
    originalWidth: ii.width,
    originalHeight: ii.height,
    sourceUrl: ii.descriptionurl,
    artist,
    license: /^public domain$/i.test(license) ? 'Public domain' : license,
    licenseUrl: md.LicenseUrl?.value?.replace(/^http:/, 'https:') ?? null,
  };
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const body = `// Generated by scripts/fetch-species-images.mjs — do not edit by hand.
// Photos: Wikimedia Commons, each under the licence listed with its author.

export interface SpeciesImage {
  /** ${THUMB_WIDTH}px thumbnail served by upload.wikimedia.org. */
  src: string;
  width: number;
  height: number;
  /** Size of the original upload (larger thumbnails are capped to it). */
  originalWidth: number;
  originalHeight: number;
  /** Commons file page: full title, author, source and licence. */
  sourceUrl: string;
  artist: string;
  license: string;
  licenseUrl: string | null;
}

export const SPECIES_IMAGES: Record<string, SpeciesImage> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(fileURLToPath(new URL('src/data/speciesImages.ts', root)), body);
console.log(`✓ ${Object.keys(out).length} images written`);
